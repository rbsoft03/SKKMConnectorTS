/**Планируемый статус товара при проверке кода маркировки (таблица 105 ФФД). */
export enum MarkingPlannedStatus{
    
    /**Не задан (значение по умолчанию в запросе). */
    NotSpecified = 0,

    /**Реализован. */
    Sold = 1,

    /**Мерный товар в стадии реализации. */
    InSale = 2,

    /**Возвращён. */
    Returned = 3,

    /**Часть товара возвращена. */
    PartiallyReturned = 4,

    /**Статус не изменился. */
    Unchanged = 255
}