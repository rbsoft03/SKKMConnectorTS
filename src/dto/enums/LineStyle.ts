/**Стиль разделительной линии: 0 — сплошная; 1 — жирная; 2 — штриховая; 3 — пунктирная; 4 — двойная.*/
export enum LineStyle{

    /**Сплошная линия (по умолчанию).*/
    Solid,

    /** Жирная линия.*/
    Bold,

    /**Штриховая линия.*/
    Dashed,

    /**Пунктирная линия.*/
    Dotted,
    
    /**Двойная линия.*/
    Double
}