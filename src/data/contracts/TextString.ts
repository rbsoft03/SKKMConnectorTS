/**Печать текстовой строки в документе.*/
export class TextString {
    
    /** Строка с произвольным текстом. */
    Text?: string;

    /** Шрифт строки: Normal, Bold, Small, Medium, Big, H1, H2, H3, H4, H5. */
    Font?: string;

    /** Выравнивание: left, right, center, width. */
    Alignment?: string;
}